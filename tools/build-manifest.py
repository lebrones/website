#!/usr/bin/env python3
"""Regenerate assets/data/photos.js from the image folders.

Run from the repo root after adding or removing photos:
    python3 tools/build-manifest.py
Photos are listed in filename order. Add a filename to HIDDEN to keep it in
the repo but leave it off the site.
"""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SETS = {"bw": "assets/images/projects/black-and-white"}
HIDDEN = {
    "23--4630alberto931.webp",   # conversion broken (mostly grey)
    "24--4630alberto931.webp",   # conversion broken (mostly grey)
    "R1-06987-0026-2.webp",      # duplicate of R1-06987-0026
}

out = {}
for key, folder in SETS.items():
    items = []
    for f in sorted(os.listdir(os.path.join(ROOT, folder))):
        if not f.lower().endswith((".webp", ".jpg", ".jpeg", ".png")) or f in HIDDEN:
            continue
        w, h = Image.open(os.path.join(ROOT, folder, f)).size
        items.append({"src": f"{folder}/{f}", "w": w, "h": h})
    out[key] = items

with open(os.path.join(ROOT, "assets/data/photos.js"), "w") as fh:
    fh.write("// Generated by tools/build-manifest.py; do not edit by hand.\n")
    fh.write("window.PHOTOS = " + json.dumps(out, indent=1) + ";\n")
print({k: len(v) for k, v in out.items()})
