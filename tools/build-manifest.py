#!/usr/bin/env python3
"""Regenerate assets/data/photos.js from the image folders and collections.json.

Run from the repo root after adding/removing photos or editing collections:
    python3 tools/build-manifest.py
Photos are listed in filename order. Add a filename to HIDDEN to keep it in
the repo but leave it off the site.
"""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TONES = {  # key: (label, folder)
    "bw": ("Black & white", "assets/images/projects/black-and-white"),
    "color": ("Colors", "assets/images/projects/colors"),
}
PREVIEW = "assets/images/preview"
HIDDEN = {
    "23--4630alberto931.webp",   # conversion broken (mostly grey)
    "24--4630alberto931.webp",   # conversion broken (mostly grey)
    "R1-06987-0026-2.webp",      # duplicate of R1-06987-0026
}

coll = json.load(open(os.path.join(ROOT, "assets/data/collections.json")))
names = [k for k in coll if not k.startswith("_")]
where = {f: name for name in names for f in coll[name]}
titles_path = os.path.join(ROOT, "assets/data/titles.json")
titles = json.load(open(titles_path)) if os.path.exists(titles_path) else {}

photos, missing = [], []
for tone, (_, folder) in TONES.items():
    d = os.path.join(ROOT, folder)
    if not os.path.isdir(d):
        continue
    for f in sorted(os.listdir(d)):
        if not f.lower().endswith((".webp", ".jpg", ".jpeg", ".png")) or f in HIDDEN:
            continue
        im = Image.open(os.path.join(d, f))
        w, h = im.size
        # small copy for the opening sequence (fast to load); only (re)made when missing or older
        stem = os.path.splitext(f)[0].replace(" ", "-")
        prev_rel = f"{PREVIEW}/{stem}.webp"
        prev = os.path.join(ROOT, prev_rel)
        if not os.path.exists(prev) or os.path.getmtime(prev) < os.path.getmtime(os.path.join(d, f)):
            os.makedirs(os.path.dirname(prev), exist_ok=True)
            small = im.convert("RGB"); small.thumbnail((1400, 1400), Image.LANCZOS)
            small.save(prev, "WEBP", quality=80)
        c = where.get(f)
        if c is None:
            missing.append(f)
        photos.append({"src": f"{folder}/{f}", "w": w, "h": h, "tone": tone, "collection": c,
                       "title": titles.get(f, ""), "preview": prev_rel})

with open(os.path.join(ROOT, "assets/data/photos.js"), "w") as fh:
    fh.write("// Generated by tools/build-manifest.py; do not edit by hand.\n")
    fh.write("window.TONES = " + json.dumps({k: v[0] for k, v in TONES.items()}) + ";\n")
    fh.write("window.COLLECTIONS = " + json.dumps(names) + ";\n")
    notes_path = os.path.join(ROOT, "assets/data/notes.json")
    notes = json.load(open(notes_path)) if os.path.exists(notes_path) else {}
    notes = {k: v for k, v in notes.items() if k != "_note"}
    fh.write("window.NOTES = " + json.dumps(notes, ensure_ascii=False, indent=1) + ";\n")
    fh.write("window.PHOTOS = " + json.dumps(photos, indent=1) + ";\n")

# bump the ?v= number in index.html so browsers fetch the new photos.js
import re, time
ix = os.path.join(ROOT, "index.html")
html = open(ix).read()
html = re.sub(r'photos\.js\?v=[0-9]+', f'photos.js?v={int(time.time())}', html)
open(ix, "w").write(html)

by = {}
for p in photos:
    by.setdefault((p["tone"], p["collection"]), 0)
    by[(p["tone"], p["collection"])] += 1
for k, v in sorted(by.items(), key=str):
    print(k, v)
if missing:
    print("Not in any collection (shown under 'All' only):", missing)
